// Regenerate src/lib/abis.ts from the compiled PerpsArena artifact.
// Run after any contract change: `npm run abis` (needs `npx hardhat compile`
// in ../contracts first). Hand-editing an ABI is how this codebase once ended
// up calling functions that did not exist on-chain.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const artifact = path.join(here, '..', '..', 'contracts', 'artifacts', 'src', 'PerpsArena.sol', 'PerpsArena.json');

if (!fs.existsSync(artifact)) {
  console.error(`Missing ${artifact}: run \`npx hardhat compile\` in ../contracts first.`);
  process.exit(1);
}

const { abi } = JSON.parse(fs.readFileSync(artifact, 'utf8'));
const out = path.join(here, '..', 'src', 'lib', 'abis.ts');
fs.writeFileSync(
  out,
  `// Generated by scripts/gen-abis.mjs from contracts/artifacts. Do not edit.\n\n` +
    `export const PERPS_ARENA_ABI = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`Wrote ${path.relative(process.cwd(), out)} (${abi.length} entries)`);
